"""
PDF design report built from the real results of the Irona checks.

Uses a small self-contained PDF 1.4 writer (no third-party dependencies). The page body stays
light so it prints well; headings and table headers use Dracula accents.
"""

import json
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from irona import theme
from irona.project import Project

ACCENT = theme.hex_to_unit_rgb(theme.PURPLE)
HEADER_BG = theme.hex_to_unit_rgb(theme.BACKGROUND)
INK = theme.hex_to_unit_rgb(theme.BACKGROUND)
BADGE_WORDS = {"PASS", "OK", "CLEAN", "LOW", "WARN", "WARNING", "MEDIUM", "FAIL", "ERROR", "HIGH", "SKIPPED", "N/A"}


class PureVectorPDF:
    """
    Pure Python Vector PDF 1.4 document builder.
    Produces clean, valid PDF files with typography, color badges, tables, line dividers,
    and automatic multi-page flow without external dependencies.
    """

    def __init__(self, page_width: float = 612.0, page_height: float = 792.0):
        self.width = page_width
        self.height = page_height
        self.margin_left = 40.0
        self.margin_right = 40.0
        self.margin_top = 45.0
        self.margin_bottom = 45.0
        self.usable_width = self.width - self.margin_left - self.margin_right

        self.pages: List[List[str]] = []
        self.fonts = {
            "F1": "/Helvetica",
            "F2": "/Helvetica-Bold",
            "F3": "/Helvetica-Oblique",
            "F4": "/Courier",
            "F5": "/Courier-Bold",
        }
        self.current_y = self.height - self.margin_top
        self.new_page()

    def new_page(self) -> None:
        """Starts a new page and resets cursor."""
        self.pages.append([])
        self.current_y = self.height - self.margin_top

    def add_op(self, op: str) -> None:
        """Appends a raw PDF stream operator to the current page."""
        self.pages[-1].append(op)

    def ensure_space(self, height: float) -> None:
        """Triggers a page break if remaining vertical space is insufficient."""
        if self.current_y - height < self.margin_bottom:
            self.draw_page_footer()
            self.new_page()
            self.draw_page_header()

    header_title = "IRONA | DESIGN REPORT"

    def draw_page_header(self, title: Optional[str] = None) -> None:
        title = title or self.header_title
        """Draws running header."""
        y = self.height - 30.0
        self.add_op(f"BT /F1 8 Tf 0.5 0.55 0.6 rg {self.margin_left:.1f} {y:.1f} Td ({self.escape_text(title)}) Tj ET")
        self.add_op(f"0.8 0.85 0.9 RG 0.5 w {self.margin_left:.1f} {y - 4:.1f} m {self.width - self.margin_right:.1f} {y - 4:.1f} l S")

    def draw_page_footer(self) -> None:
        """Draws running footer with page number placeholder."""
        y = 25.0
        self.add_op(f"0.8 0.85 0.9 RG 0.5 w {self.margin_left:.1f} {y + 12:.1f} m {self.width - self.margin_right:.1f} {y + 12:.1f} l S")
        self.add_op(f"BT /F1 8 Tf 0.5 0.55 0.6 rg {self.margin_left:.1f} {y:.1f} Td (Generated by Irona for KiCad) Tj ET")
        page_num = len(self.pages)
        self.add_op(f"BT /F1 8 Tf 0.5 0.55 0.6 rg {self.width - self.margin_right - 45:.1f} {y:.1f} Td (Page {page_num}) Tj ET")

    @staticmethod
    def escape_text(text: str) -> str:
        """Escapes and normalizes text for standard PDF Type 1 fonts."""
        s = str(text)
        # Normalize common engineering symbols to standard ASCII
        replacements = {
            "Ω": " Ohm",
            "μ": "u",
            "±": "+/-",
            "°": " deg ",
            "ε": "eps",
            "–": "-",
            "—": "--",
            "’": "'",
            "“": '"',
            "”": '"',
            "•": "*",
            "→": "->",
            "≤": "<=",
            "≥": ">=",
        }
        for k, v in replacements.items():
            s = s.replace(k, v)
        # Ensure pure ASCII / latin1 compatibility
        s = s.encode("latin1", errors="replace").decode("latin1")
        return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")

    def draw_text(self, x: float, y: float, text: str, size: float = 10.0, font: str = "/F1", color: Tuple[float, float, float] = (0.1, 0.1, 0.15)) -> None:
        r, g, b = color
        safe = self.escape_text(text)
        self.add_op(f"BT {font} {size:.1f} Tf {r:.2f} {g:.2f} {b:.2f} rg {x:.1f} {y:.1f} Td ({safe}) Tj ET")

    def draw_rect(self, x: float, y: float, w: float, h: float, fill_color: Optional[Tuple[float, float, float]] = None, stroke_color: Optional[Tuple[float, float, float]] = None, line_width: float = 1.0) -> None:
        ops = []
        if fill_color:
            r, g, b = fill_color
            ops.append(f"{r:.2f} {g:.2f} {b:.2f} rg")
        if stroke_color:
            r, g, b = stroke_color
            ops.append(f"{r:.2f} {g:.2f} {b:.2f} RG {line_width:.1f} w")
        ops.append(f"{x:.1f} {y:.1f} {w:.1f} {h:.1f} re")
        if fill_color and stroke_color:
            ops.append("b")
        elif fill_color:
            ops.append("f")
        elif stroke_color:
            ops.append("s")
        self.add_op(" ".join(ops))

    def draw_line(self, x1: float, y1: float, x2: float, y2: float, color: Tuple[float, float, float] = (0.8, 0.85, 0.9), line_width: float = 1.0) -> None:
        r, g, b = color
        self.add_op(f"{r:.2f} {g:.2f} {b:.2f} RG {line_width:.1f} w {x1:.1f} {y1:.1f} m {x2:.1f} {y2:.1f} l S")

    def add_section_header(self, title: str, subtitle: Optional[str] = None) -> None:
        """Adds a section banner with an accent indicator."""
        needed = 45.0 if subtitle else 32.0
        self.ensure_space(needed)
        y = self.current_y

        # Accent bar
        self.draw_rect(self.margin_left, y - 20, 5, 20, fill_color=ACCENT)
        # Title text
        self.draw_text(self.margin_left + 12, y - 15, title.upper(), size=12, font="/F2", color=INK)
        self.draw_line(self.margin_left + 12, y - 20, self.width - self.margin_right, y - 20, color=(0.85, 0.88, 0.92), line_width=1.0)

        self.current_y -= 26
        if subtitle:
            self.draw_text(self.margin_left + 12, self.current_y - 6, subtitle, size=8.5, font="/F3", color=(0.4, 0.45, 0.55))
            self.current_y -= 20

    def add_badge(self, x: float, y: float, text: str, status: str = "PASS") -> float:
        """Draws a status badge (PASS, WARN, FAIL, INFO). Returns badge width."""
        # Order matters: check failures first so e.g. "FAIL" is never matched as a pass.
        status = status.upper()
        if any(k in status for k in ("FAIL", "BLOCK", "ERROR", "HIGH")):
            bg, fg, border = (1.0, 0.92, 0.92), (0.8, 0.15, 0.15), (0.95, 0.65, 0.65)
        elif any(k in status for k in ("WARN", "MEDIUM")):
            bg, fg, border = (1.0, 0.97, 0.88), (0.75, 0.45, 0.05), (0.95, 0.8, 0.5)
        elif any(k in status for k in ("PASS", "OK", "LOW", "CLEAN")):
            bg, fg, border = (0.9, 0.98, 0.92), (0.05, 0.55, 0.25), (0.6, 0.85, 0.7)
        else:
            bg, fg, border = (0.92, 0.95, 1.0), (0.1, 0.35, 0.75), (0.7, 0.8, 0.95)

        w = max(45.0, len(text) * 5.5 + 10.0)
        h = 13.0
        self.draw_rect(x, y - 2, w, h, fill_color=bg, stroke_color=border, line_width=0.7)
        self.draw_text(x + 5, y + 1.5, text, size=7.5, font="/F5", color=fg)
        return w

    def add_callout(self, text: str, label: str = "NOTE", status: str = "INFO") -> None:
        """Draws a callout box."""
        self.ensure_space(32.0)
        y = self.current_y
        w = self.usable_width
        h = 24.0

        bg = (0.96, 0.98, 1.0)
        accent = (0.1, 0.45, 0.85)
        if status == "FAIL":
            bg = (1.0, 0.94, 0.94)
            accent = (0.8, 0.15, 0.15)
        elif status == "PASS":
            bg = (0.94, 0.99, 0.95)
            accent = (0.1, 0.65, 0.3)
        elif status == "WARN":
            bg = (1.0, 0.98, 0.92)
            accent = (0.85, 0.55, 0.1)

        self.draw_rect(self.margin_left, y - h, w, h, fill_color=bg, stroke_color=(0.85, 0.9, 0.95), line_width=0.8)
        self.draw_rect(self.margin_left, y - h, 4, h, fill_color=accent)
        line = f"[{label}] {text}"
        max_chars = int((w - 16) / 4.5)
        if len(line) > max_chars:
            line = line[: max_chars - 1] + "~"
        self.draw_text(self.margin_left + 10, y - 16, line, size=8.5, font="/F1", color=(0.15, 0.2, 0.3))
        self.current_y -= (h + 8)

    def add_table(self, headers: List[str], rows: List[List[str]], col_widths: Optional[List[float]] = None) -> None:
        """Draws a structured data table with headers and alternating row fills."""
        n_cols = len(headers)
        if not col_widths:
            w_each = self.usable_width / n_cols
            col_widths = [w_each] * n_cols

        # Header
        self.ensure_space(20.0 + len(rows) * 16.0)
        y = self.current_y
        h_h = 18.0

        # Header background
        self.draw_rect(self.margin_left, y - h_h, self.usable_width, h_h, fill_color=HEADER_BG, stroke_color=HEADER_BG)
        cur_x = self.margin_left
        for i, h in enumerate(headers):
            self.draw_text(cur_x + 6, y - 13, str(h).upper(), size=8.0, font="/F2", color=(1.0, 1.0, 1.0))
            cur_x += col_widths[i]

        self.current_y -= h_h

        # Rows
        row_h = 16.0
        for r_idx, row in enumerate(rows):
            self.ensure_space(row_h)
            y = self.current_y
            bg = (0.98, 0.985, 0.99) if r_idx % 2 == 0 else (1.0, 1.0, 1.0)
            self.draw_rect(self.margin_left, y - row_h, self.usable_width, row_h, fill_color=bg, stroke_color=(0.88, 0.9, 0.94), line_width=0.5)

            cur_x = self.margin_left
            for c_idx, cell in enumerate(row):
                if c_idx < len(col_widths):
                    val = str(cell)
                    max_chars = max(4, int((col_widths[c_idx] - 10) / 4.3))
                    if len(val) > max_chars:
                        val = val[: max_chars - 1] + "~"
                    # Detect badge inside cell
                    if val in BADGE_WORDS:
                        self.add_badge(cur_x + 6, y - 13, val, val)
                    else:
                        font = "/F5" if c_idx == 0 else "/F1"
                        self.draw_text(cur_x + 6, y - 12, val, size=8.0, font=font, color=(0.15, 0.2, 0.25))
                    cur_x += col_widths[c_idx]

            self.current_y -= row_h

        self.current_y -= 8

    def build(self) -> bytes:
        """Serializes all pages and objects into compliant PDF 1.4 binary data."""
        # Ensure last page has footer
        self.draw_page_footer()

        objs: Dict[int, bytes] = {}
        next_id = 1

        catalog_id = next_id; next_id += 1
        pages_id = next_id; next_id += 1

        # Font definitions
        font_ids = {}
        for fname, base in self.fonts.items():
            font_ids[fname] = next_id
            objs[next_id] = f"<< /Type /Font /Subtype /Type1 /BaseFont {base} >>".encode("latin1")
            next_id += 1

        font_res = " ".join(f"/{k} {v} 0 R" for k, v in font_ids.items())

        # Page and Stream definitions
        page_ids = []
        for p_stream in self.pages:
            content = "\n".join(p_stream).encode("latin1")
            stream_id = next_id; next_id += 1
            objs[stream_id] = f"<< /Length {len(content)} >>\nstream\n".encode("latin1") + content + b"\nendstream"
            page_id = next_id; next_id += 1
            page_ids.append(page_id)
            objs[page_id] = f"<< /Type /Page /Parent {pages_id} 0 R /MediaBox [0 0 {self.width:.1f} {self.height:.1f}] /Contents {stream_id} 0 R /Resources << /Font << {font_res} >> >> >>".encode("latin1")

        kids = " ".join(f"{pid} 0 R" for pid in page_ids)
        objs[pages_id] = f"<< /Type /Pages /Kids [{kids}] /Count {len(page_ids)} >>".encode("latin1")
        objs[catalog_id] = f"<< /Type /Catalog /Pages {pages_id} 0 R >>".encode("latin1")

        # Serialize objects in ascending numerical order
        out: List[bytes] = [b"%PDF-1.4\n"]
        offsets: Dict[int, int] = {}
        for oid in range(1, next_id):
            offsets[oid] = sum(len(x) for x in out)
            out.append(f"{oid} 0 obj\n".encode("latin1") + objs[oid] + b"\nendobj\n")

        xref_pos = sum(len(x) for x in out)
        out.append(f"xref\n0 {next_id}\n0000000000 65535 f \n".encode("latin1"))
        for oid in range(1, next_id):
            out.append(f"{offsets[oid]:010d} 00000 n \n".encode("latin1"))

        out.append(f"trailer\n<< /Size {next_id} /Root {catalog_id} 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n".encode("latin1"))
        return b"".join(out)


class DesignReportPDF:
    """Runs every check on a project and lays the results out as a PDF."""

    MAX_ROWS = 30

    def __init__(self, project_dir: Path, output_pdf_path: Optional[Path] = None):
        self.project = Project(project_dir)
        self.output_pdf_path = Path(output_pdf_path) if output_pdf_path else self.project.output_dir / f"{self.project.name}_report.pdf"
        self.output_pdf_path.parent.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------ data
    def gather_data(self) -> Dict[str, Any]:
        from irona.drc import DRCEngine
        from irona.erc import ERCEngine
        from irona.sipi_review import SIPIReviewer
        from irona.circuit_review import CircuitReviewer
        from irona.simulation import BoardSimulator

        pr = self.project
        data: Dict[str, Any] = {
            "project": pr.name,
            "date": time.strftime("%Y-%m-%d %H:%M"),
            "sch": pr.sch.name if pr.sch else None,
            "pcb": pr.pcb.name if pr.pcb else None,
            "errors": [],
        }

        def attempt(key: str, fn) -> None:
            try:
                data[key] = fn()
            except Exception as e:  # report what failed instead of aborting the whole report
                data[key] = None
                data["errors"].append(f"{key}: {e}")

        sim_inputs = pr.load_sim_inputs()
        if pr.pcb:
            attempt("drc", lambda: DRCEngine(pr.pcb).run_drc())
            attempt("sipi", lambda: SIPIReviewer(pr.pcb, pr.sch, pr.netlist, sim_inputs).generate_review_report())
            if sim_inputs and sim_inputs.get("load_currents_A"):
                attempt("sim", lambda: BoardSimulator(pr.pcb, ambient_temp_c=sim_inputs.get("ambient_temp_c", 25.0), **sim_inputs.get("limits", {})).evaluate(
                    sim_inputs.get("load_currents_A"), sim_inputs.get("power_dissipation_W")))
        if pr.sch:
            attempt("erc", lambda: ERCEngine(pr.sch, pr.netlist).run_erc())
        if pr.sch and pr.pcb:
            attempt("circuit", lambda: CircuitReviewer().run_full_analysis(pr.sch, pr.pcb, pr.output_dir / "circuit-review"))
        data["bom"] = self._bom()
        return data

    def _bom(self) -> List[List[str]]:
        """Grouped BOM rows [refs, value, footprint, qty] from the netlist JSON or the board."""
        parts: List[Tuple[str, str, str]] = []
        nl = self.project.netlist
        if nl:
            try:
                for c in json.loads(nl.read_text(encoding="utf-8")).get("components", []):
                    parts.append((c.get("ref", "?"), c.get("value", ""), c.get("footprint", "")))
            except (OSError, ValueError):
                parts = []
        if not parts and self.project.pcb:
            from irona.docs import read_board_footprints
            parts = [(fp["ref"], fp["value"], fp["footprint"]) for fp in read_board_footprints(self.project.pcb)]
        return group_bom(parts)

    # ------------------------------------------------------------------ layout
    def generate_pdf(self) -> Path:
        d = self.gather_data()
        pdf = PureVectorPDF()
        pdf.header_title = f"IRONA | {d['project'].upper()} DESIGN REPORT"

        pdf.draw_rect(pdf.margin_left, pdf.height - 100, pdf.usable_width, 55, fill_color=HEADER_BG)
        pdf.draw_text(pdf.margin_left + 16, pdf.height - 68, d["project"], size=16, font="/F2", color=theme.hex_to_unit_rgb(theme.FOREGROUND))
        pdf.draw_text(pdf.margin_left + 16, pdf.height - 88, f"Design report  |  {d['date']}  |  {d['sch'] or 'no schematic'}  |  {d['pcb'] or 'no board'}",
                      size=8.5, font="/F1", color=theme.hex_to_unit_rgb(theme.PURPLE))
        pdf.current_y = pdf.height - 120

        self._summary(pdf, d)
        self._drc_erc(pdf, d)
        self._simulation(pdf, d)
        self._sipi(pdf, d)
        self._circuit(pdf, d)

        pdf.add_section_header("Bill of materials", f"{sum(int(r[3]) for r in d['bom'])} parts, {len(d['bom'])} lines")
        if d["bom"]:
            pdf.add_table(["References", "Value", "Footprint", "Qty"], d["bom"], [150, 120, 222, 40])
        else:
            pdf.add_callout("No components found in netlist or board.", label="BOM", status="INFO")

        if d["errors"]:
            pdf.add_section_header("Checks that could not run")
            for e in d["errors"]:
                pdf.add_callout(e, label="ERROR", status="FAIL")

        self.output_pdf_path.write_bytes(pdf.build())
        return self.output_pdf_path

    @staticmethod
    def _status(ok: Optional[bool]) -> str:
        return "N/A" if ok is None else ("PASS" if ok else "FAIL")

    def _summary(self, pdf: "PureVectorPDF", d: Dict[str, Any]) -> None:
        pdf.add_section_header("Summary")
        rows = []
        if d.get("erc") is not None:
            e = d["erc"]
            rows.append(["ERC", f"{e['error_count']} errors, {e['warning_count']} warnings", self._status(e["error_count"] == 0)])
        if d.get("drc") is not None:
            rows.append(["DRC", f"{d['drc']['error_count']} violations", self._status(d["drc"]["error_count"] == 0)])
        if d.get("sim") is not None:
            s = d["sim"]
            rows.append(["Simulation", f"IR drop {s['power_integrity']['max_voltage_drop_mv']} mV, hotspot {s['thermal']['max_junction_temp_c']} C", s["status"]])
        else:
            rows.append(["Simulation", "No load currents configured (run the Simulator plugin)", "SKIPPED"])
        if d.get("sipi") is not None:
            r = d["sipi"]
            rows.append(["SI/PI review", f"{r['overall_score']}% ({r['letter_grade']}), {len(r['critical_findings'])} critical, {len(r['warning_findings'])} warnings",
                         "FAIL" if r["critical_findings"] else ("WARN" if r["warning_findings"] else "PASS")])
        if d.get("circuit") is not None:
            c = d["circuit"]
            fc = c["findings_count"]
            rows.append(["Circuit review", f"{fc['error']} errors, {fc['warning']} warnings, {fc['info']} info",
                         "FAIL" if fc["error"] else ("WARN" if fc["warning"] else "PASS")])
            emc = c["emc_summary"].get("emc_risk_score")
            rows.append(["EMC pre-compliance", f"risk score {emc}/100" if emc is not None else f"unavailable: {c.get('emc_error')}", "N/A" if emc is None else ("PASS" if emc >= 80 else "WARN")])
            for fab, label in (("jlcpcb", "JLCPCB"), ("pcbway", "PCBWay")):
                a = c["dfm_audit"][fab]
                rows.append([f"DFM {label}", f"{a['score']:.0f}% of checks pass", "PASS" if a["compatible"] else "FAIL"])
        pdf.add_table(["Check", "Result", "Status"], rows, [130, 330, 72])

    def _drc_erc(self, pdf: "PureVectorPDF", d: Dict[str, Any]) -> None:
        drc = (d.get("drc") or {}).get("violations", [])
        erc = (d.get("erc") or {}).get("violations", []) + (d.get("erc") or {}).get("warnings", [])
        if not drc and not erc:
            return
        pdf.add_section_header("Rule check violations")
        def row(kind, v):
            if isinstance(v, dict):
                return [kind, str(v.get("rule", "")), str(v.get("description", v))]
            return [kind, "", str(v)]
        rows = [row("DRC", v) for v in drc[: self.MAX_ROWS]] + [row("ERC", v) for v in erc[: self.MAX_ROWS]]
        pdf.add_table(["Check", "Type", "Detail"], rows, [50, 110, 372])

    def _simulation(self, pdf: "PureVectorPDF", d: Dict[str, Any]) -> None:
        s = d.get("sim")
        if s is None:
            return
        pdf.add_section_header("Simulation", "Closed-form DC IR drop, current density and lumped thermal estimate")
        rows = [[net, f"{v['load_current_A']:g}", f"{v['trace_resistance_mOhm']}", f"{v['voltage_drop_mV']}", f"{v['max_current_density_A_mm2']}"]
                for net, v in s["power_integrity"]["nets"].items()]
        pdf.add_table(["Net", "Current (A)", "R (mOhm)", "Drop (mV)", "J (A/mm2)"], rows)
        t = s["thermal"]
        pdf.add_table(["Ambient (C)", "Hotspot (C)", "Rise (C)", "Power (W)", "Theta (C/W)"],
                      [[f"{t['ambient_temp_c']}", f"{t['max_junction_temp_c']}", f"{t['delta_temp_c']}", f"{t['total_power_dissipation_w']}", f"{t['theta_ja_c_per_w']}"]])
        for msg in s["layout_feedback"]:
            pdf.add_callout(msg, label=s["status"], status=s["status"])

    def _sipi(self, pdf: "PureVectorPDF", d: Dict[str, Any]) -> None:
        r = d.get("sipi")
        if r is None:
            return
        pdf.add_section_header("SI/PI and IPC review", f"Score {r['overall_score']}% ({r['letter_grade']})")
        rows = [[c["name"], f"{c['score']}"] for c in r["categories"]]
        pdf.add_table(["Category", "Score"], rows, [440, 92])
        findings = [("FAIL", f) for f in r["critical_findings"]] + [("WARN", f) for f in r["warning_findings"]]
        if findings:
            pdf.add_table(["Severity", "Finding"], [[s, f.lstrip("❌⚠️✅ ").strip()] for s, f in findings[: self.MAX_ROWS]], [60, 472])

    def _circuit(self, pdf: "PureVectorPDF", d: Dict[str, Any]) -> None:
        c = d.get("circuit")
        if c is None:
            return
        pdf.add_section_header("Circuit review", f"Score {c['overall_score']} ({c['grade']})")
        fmt = lambda v, u="": "unknown" if v is None else f"{v}{u}"
        rails = c["power_tree"]["rails"]
        if rails:
            pdf.add_table(["Rail", "Voltage"], [[r["rail"], fmt(r["voltage"], " V")] for r in rails], [266, 266])
        regs = c["power_tree"]["regulators"]
        if regs:
            pdf.add_table(["Regulator", "Part", "Topology", "Vout"],
                          [[r["ref"], r.get("part", ""), fmt(r.get("topology")), fmt(r.get("estimated_vout"), " V")] for r in regs])
        sev_map = {"error": "ERROR", "warning": "WARN", "info": "INFO"}
        rows = [[sev_map.get(f["severity"], f["severity"].upper()), f["rule_id"], f["summary"]]
                for f in c["findings"] if f["severity"] in ("error", "warning")][: self.MAX_ROWS]
        if rows:
            pdf.add_table(["Severity", "Rule", "Finding"], rows, [60, 70, 402])


def group_bom(parts: List[Tuple[str, str, str]]) -> List[List[str]]:
    """[(ref, value, footprint)] -> [[refs, value, footprint, qty]] grouped by value+footprint."""
    groups: Dict[Tuple[str, str], List[str]] = {}
    for ref, value, fp in parts:
        groups.setdefault((value, fp), []).append(ref)
    rows = []
    for (value, fp), refs in sorted(groups.items(), key=lambda kv: kv[1][0]):
        rows.append([", ".join(sorted(refs)), value, fp.split(":")[-1], str(len(refs))])
    return rows
